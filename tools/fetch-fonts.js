// Downloads the open (OFL) web fonts the plugin can recognise on a screenshot and writes what the plugin reads:
//   assets/fonts/<slug>-<subset>.woff2   the Latin and Cyrillic subsets of each family
//   assets/fonts/fonts.json              slug, name, kind (sans/serif/mono) and CSS stack of each family
//   assets/fonts.css                     @font-face rules and one class per family (pg-font-<slug>)
// Monospaced families are left out on purpose: they all advance by .6 em, so the widths of words cannot tell them apart.
// Run it again after changing the list (`node tools/fetch-fonts.js`); it needs network access, the plugin itself does not.
// The fonts come from Google Fonts and are licensed under the SIL Open Font License 1.1 (see assets/fonts/OFL.txt).
const fs = require('fs');
const path = require('path');

const FAMILIES = [
    // slug, Google family name, kind, weights ("400..700" for a variable font, "400;700" for static ones)
    ['inter', 'Inter', 'sans', '400..700'],
    ['roboto', 'Roboto', 'sans', '400..700'],
    ['open-sans', 'Open Sans', 'sans', '400..700'],
    ['noto-sans', 'Noto Sans', 'sans', '400..700'],
    ['montserrat', 'Montserrat', 'sans', '400..700'],
    ['source-sans-3', 'Source Sans 3', 'sans', '400..700'],
    ['pt-sans', 'PT Sans', 'sans', '400;700'],
    ['rubik', 'Rubik', 'sans', '400..700'],
    ['merriweather', 'Merriweather', 'serif', '400..700'],
    ['pt-serif', 'PT Serif', 'serif', '400;700'],
    ['playfair-display', 'Playfair Display', 'serif', '400..700'],
    ['noto-serif', 'Noto Serif', 'serif', '400..700']
];
const FALLBACK = {
    sans: 'Arial,Helvetica,sans-serif',
    serif: "Georgia,'Times New Roman',serif",
    mono: "ui-monospace,SFMono-Regular,Menlo,Consolas,'Liberation Mono',monospace"
};
const SUBSETS = ['latin', 'cyrillic'];
const AGENT = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const root = path.join(__dirname, '..', 'assets');
const folder = path.join(root, 'fonts');

async function get(url, binary) {
    const response = await fetch(url, { headers: { 'User-Agent': AGENT } });
    if (!response.ok) throw new Error(url + ' -> HTTP ' + response.status);
    return binary ? Buffer.from(await response.arrayBuffer()) : response.text();
}

(async () => {
    fs.mkdirSync(folder, { recursive: true });
    const registry = [];
    let css = '/* Generated by tools/fetch-fonts.js: do not edit. Fonts: SIL Open Font License 1.1 (assets/fonts/OFL.txt). */\n';
    let rules = '';
    for (const [slug, name, kind, weights] of FAMILIES) {
        const sheet = await get('https://fonts.googleapis.com/css2?family=' + name.replace(/ /g, '+') + ':wght@' + weights + '&display=swap', false);
        const blocks = sheet.split(/\/\*\s*([a-z-]+)\s*\*\//).slice(1);
        let faces = 0;
        for (let index = 0; index < blocks.length; index += 2) {
            const subset = blocks[index];
            const body = blocks[index + 1];
            if (SUBSETS.indexOf(subset) === -1) continue;
            const url = /url\((https:[^)]+\.woff2)\)/.exec(body);
            const range = /unicode-range:\s*([^;]+);/.exec(body);
            const weight = /font-weight:\s*([^;]+);/.exec(body);
            if (!url || !range || !weight) continue;
            // Static families come as one file per weight: the weight is part of the file name.
            const file = slug + '-' + subset + (weights.indexOf('..') === -1 ? '-' + weight[1].trim().replace(/\s+/g, '-') : '') + '.woff2';
            fs.writeFileSync(path.join(folder, file), await get(url[1], true));
            css += "@font-face{font-family:'" + name + "';font-style:normal;font-weight:" + weight[1].trim() + ';font-display:swap;src:url(fonts/' + file + ") format('woff2');unicode-range:" + range[1].trim() + '}\n';
            faces += 1;
        }
        if (!faces) throw new Error('no faces found for ' + name);
        const stack = "'" + name + "'," + FALLBACK[kind];
        registry.push({ slug, name, kind, stack });
        // The class sits on a block (Gutenberg) or a widget (Elementor): everything inside takes the face.
        rules += '.page-generator-canvas .pg-font-' + slug + ',.page-generator-canvas .pg-font-' + slug + ' a,.pg-flow-page .pg-font-' + slug + ',.pg-flow-page .pg-font-' + slug + ' a,' +
            '.page-generator-canvas .elementor-widget.pg-font-' + slug + ' *{font-family:' + stack + '}\n';
        console.log(slug, faces + ' files');
    }
    fs.writeFileSync(path.join(folder, 'fonts.json'), JSON.stringify(registry, null, 2) + '\n');
    fs.writeFileSync(path.join(root, 'fonts.css'), css + rules);
    let total = 0;
    fs.readdirSync(folder).forEach((name) => { if (/\.woff2$/.test(name)) total += fs.statSync(path.join(folder, name)).size; });
    console.log('fonts: ' + registry.length + ' families, ' + Math.round(total / 1024) + ' KB of woff2');
})().catch((error) => { console.error(error.message); process.exit(1); });
